/* ----------------------------------------------------------------------------
   [1] DDL — equivalent of the AddInstructorSelfService migration
 --------------------------------------------------------------------------- */
IF NOT EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID(N'[dbo].[Instructors]')
      AND name = N'HourlyRate')
BEGIN
    ALTER TABLE [dbo].[Instructors]
        ADD [HourlyRate] decimal(10,2) NOT NULL
        CONSTRAINT [DF_Instructors_HourlyRate] DEFAULT (0);
END
GO

/* ----------------------------------------------------------------------------
   [2] BACKFILL — MANDATORY, run after [1]

   HourlyRate moves onto Instructor as the live, instructor-editable price.
   EF Core creates the column with DEFAULT 0, so every existing instructor
   would land at $0.00. That silently breaks three things that already read
   the rate:

     - GetInstructorsForLearnerQueryHandler  -> MinPrice/MaxPrice budget filter
     - GetInstructorsForLearnerQueryHandler  -> ascending price sort
     - GetInstructorAvailabilityForLearnerQueryHandler -> the rate shown to learners

   Seed each instructor from the rate they submitted with their application.
 --------------------------------------------------------------------------- */
UPDATE i
SET    i.[HourlyRate] = a.[HourlyRate]
FROM   [dbo].[Instructors] AS i
JOIN   [dbo].[InstructorApplications] AS a
       ON a.[InstructorId] = i.[Id]
      AND a.[IsDeleted] = 0
WHERE  i.[HourlyRate] = 0
  AND  a.[HourlyRate] > 0;
GO

/* ----------------------------------------------------------------------------
   [3] VERIFY — expect 0 rows. Any row here has no usable rate and will show
   as free to learners; resolve it before enabling the profile editor.
 --------------------------------------------------------------------------- */
SELECT i.[Id], i.[UserId], i.[HourlyRate], a.[Status]
FROM   [dbo].[Instructors] AS i
LEFT JOIN [dbo].[InstructorApplications] AS a
       ON a.[InstructorId] = i.[Id] AND a.[IsDeleted] = 0
WHERE  i.[IsDeleted] = 0
  AND  (i.[HourlyRate] <= 0 OR i.[HourlyRate] IS NULL);
GO

